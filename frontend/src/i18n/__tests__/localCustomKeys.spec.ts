function getMessage(messages: Record<string, unknown>, key: string): unknown {
  return key.split('.').reduce<unknown>((value, segment) => {
    if (!value || typeof value !== 'object') return undefined
    return (value as Record<string, unknown>)[segment]
  }, messages)
}

describe.each([
  ['en', en],
  ['zh', zh],
] as const)('%s local locale keys', (_locale, messages) => {
  it.each(requiredLocalKeys)('contains %s', (key) => {
    expect(getMessage(messages, key)).toEqual(expect.any(String))
  })
})
